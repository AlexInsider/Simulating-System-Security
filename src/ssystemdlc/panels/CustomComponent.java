    private void submitBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_submitBtnActionPerformed
        if(username.getText().isEmpty() || password.getText().isEmpty() || roles.getSelectedItem() == null){
            JOptionPane.showMessageDialog(this, "Please Fill All Fields!", "Empty Field", JOptionPane.ERROR_MESSAGE);
            return;
        }

        String query = "";

        if(mode.equals("Edit")){
            query = "UPDATE users SET username = ?, password = ?, role = ? WHERE username = ?";
        }else{
            query = "INSERT INTO users VALUES (null, ?, ?, ?)";
        }

        try{
            PreparedStatement pst = conn.prepareStatement(query);

            if(mode.equals("Edit")){
                pst.setString(1, username.getText());
                pst.setString(2, password.getText());
                pst.setString(3, roles.getSelectedItem().toString());
                pst.setString(4, usrname);
            }else{
                pst.setString(1, username.getText());
                pst.setString(2, password.getText());
                pst.setString(3, roles.getSelectedItem().toString());
            }

            pst.execute();
            JOptionPane.showMessageDialog(this, mode +"ed Successfully!", "OK", JOptionPane.INFORMATION_MESSAGE);
            home.updateContentTable();
            this.dispose();
        }catch(SQLException e){
            e.printStackTrace();
        }
    }//GEN-LAST:event_submitBtnActionPerformed

